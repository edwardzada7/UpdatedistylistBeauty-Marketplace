-- ---------------------------------------------------------------- certificates
CREATE TABLE IF NOT EXISTS provider_certifications (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_auth_id   UUID NOT NULL,
    specialty          TEXT,
    certification_name TEXT,
    certificate_url    TEXT,
    expiry_date        DATE,
    status             TEXT NOT NULL DEFAULT 'pending',
    is_active          BOOLEAN NOT NULL DEFAULT FALSE,
    rejection_reason   TEXT,
    verified_at        TIMESTAMPTZ,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
-- If the table already existed, make sure every column the server writes is there.
ALTER TABLE provider_certifications ADD COLUMN IF NOT EXISTS specialty          TEXT;
ALTER TABLE provider_certifications ADD COLUMN IF NOT EXISTS certification_name TEXT;
ALTER TABLE provider_certifications ADD COLUMN IF NOT EXISTS certificate_url    TEXT;
ALTER TABLE provider_certifications ADD COLUMN IF NOT EXISTS expiry_date        DATE;
ALTER TABLE provider_certifications ADD COLUMN IF NOT EXISTS status             TEXT NOT NULL DEFAULT 'pending';
ALTER TABLE provider_certifications ADD COLUMN IF NOT EXISTS is_active          BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE provider_certifications ADD COLUMN IF NOT EXISTS rejection_reason   TEXT;
ALTER TABLE provider_certifications ADD COLUMN IF NOT EXISTS verified_at        TIMESTAMPTZ;
ALTER TABLE provider_certifications ADD COLUMN IF NOT EXISTS created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW();
ALTER TABLE provider_certifications ADD COLUMN IF NOT EXISTS updated_at         TIMESTAMPTZ NOT NULL DEFAULT NOW();
CREATE INDEX IF NOT EXISTS idx_provider_certifications_provider ON provider_certifications (provider_auth_id, created_at DESC);
ALTER TABLE provider_certifications ENABLE ROW LEVEL SECURITY;  -- server uses the service role key

-- -------------------------------------------------------------------- invoices
-- The server already inserts into "invoices"; only add columns that may be missing.
ALTER TABLE IF EXISTS invoices ADD COLUMN IF NOT EXISTS service_date      TEXT;
ALTER TABLE IF EXISTS invoices ADD COLUMN IF NOT EXISTS service_time      TEXT;
ALTER TABLE IF EXISTS invoices ADD COLUMN IF NOT EXISTS location          TEXT;
ALTER TABLE IF EXISTS invoices ADD COLUMN IF NOT EXISTS service_type      TEXT;
ALTER TABLE IF EXISTS invoices ADD COLUMN IF NOT EXISTS note              TEXT;
ALTER TABLE IF EXISTS invoices ADD COLUMN IF NOT EXISTS payment_reference TEXT;

-- Column types follow whatever invoices.id / provider_services.id / products.id use.
DO $$
DECLARE
    inv_type TEXT;
    svc_type TEXT;
    prod_type TEXT;
BEGIN
    SELECT format_type(a.atttypid, a.atttypmod) INTO inv_type
      FROM pg_attribute a WHERE a.attrelid = 'public.invoices'::regclass AND a.attname = 'id';
    IF inv_type IS NULL THEN
        RAISE EXCEPTION 'The invoices table was not found; cannot create invoice_items.';
    END IF;
    SELECT COALESCE((SELECT format_type(a.atttypid, a.atttypmod) FROM pg_attribute a
                      WHERE a.attrelid = to_regclass('public.provider_services') AND a.attname = 'id'), 'BIGINT') INTO svc_type;
    SELECT COALESCE((SELECT format_type(a.atttypid, a.atttypmod) FROM pg_attribute a
                      WHERE a.attrelid = to_regclass('public.products') AND a.attname = 'id'), 'BIGINT') INTO prod_type;

    EXECUTE format($f$
        CREATE TABLE IF NOT EXISTS invoice_items (
            id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            invoice_id %s NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
            service_id %s,
            product_id %s,
            quantity   INTEGER NOT NULL DEFAULT 1,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )$f$, inv_type, svc_type, prod_type);
END $$;
ALTER TABLE invoice_items ADD COLUMN IF NOT EXISTS quantity   INTEGER NOT NULL DEFAULT 1;
ALTER TABLE invoice_items ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT NOW();
CREATE INDEX IF NOT EXISTS idx_invoice_items_invoice ON invoice_items (invoice_id);
ALTER TABLE invoice_items ENABLE ROW LEVEL SECURITY;  -- server uses the service role key

